-- First supported HSQLDB Search installation. Core migrations run separately first.
-- This does not adopt a copied Sandbox projection. Preserve/archive that projection explicitly
-- before installing this rebuildable schema; authoritative Git packs and refs are untouched.
-- HSQLDialect maps Instant/TIMESTAMP_UTC to timestamp without a time-zone suffix.

create table git_commit_index (
    id bigint generated by default as identity not null,
    projection_key varchar(36) not null,
    index_profile varchar(32) not null,
    repository_name varchar(255) not null,
    object_id varchar(40) not null,
    short_message varchar(2048),
    full_message varchar(8192),
    author_name varchar(255),
    author_email varchar(255),
    author_time timestamp(6),
    committer_name varchar(255),
    committer_email varchar(255),
    commit_time timestamp(6),
    changed_paths varchar(16384),
    changed_text varchar(262144),
    primary key (id),
    constraint uk_commit_projection_key unique (projection_key),
    constraint uk_commit_repo_object unique (repository_name, object_id)
);

create index idx_commit_repo on git_commit_index (repository_name);
create index idx_commit_repo_time on git_commit_index (repository_name, commit_time);
create index idx_commit_repo_author_time on git_commit_index (repository_name, author_time);
create index idx_commit_repo_author on git_commit_index (repository_name, author_email);
create index idx_commit_repo_committer on git_commit_index (repository_name, committer_email);

comment on table git_commit_index is
    'Rebuildable generic Git commit search projection; managed by jgit-storage-hibernate-search';
