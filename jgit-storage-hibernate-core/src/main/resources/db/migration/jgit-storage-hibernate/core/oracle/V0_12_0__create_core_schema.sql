-- Initial fresh-schema migration for Oracle Free 23.26.3 (native SQL BOOLEAN).
create table git_repository_lifecycle (
    repository_name nvarchar2(255) not null,
    created_at timestamp(9) with time zone not null,
    constraint pk_git_repository_lifecycle primary key (repository_name)
);

create table git_repository_lock (
    repository_name nvarchar2(255) not null,
    created_at timestamp(9) with time zone not null,
    constraint pk_git_repository_lock primary key (repository_name),
    constraint fk_repository_lock_lifecycle foreign key (repository_name)
        references git_repository_lifecycle (repository_name) on delete cascade
);

create table git_packs (
    id number(19,0) generated by default as identity not null,
    repository_name nvarchar2(255) not null,
    pack_name nvarchar2(255) not null,
    pack_extension varchar2(32 char) not null,
    data blob,
    file_size number(19,0) not null,
    committed boolean not null,
    write_token varchar2(36 char),
    write_lease_until timestamp(9) with time zone,
    created_at timestamp(9) with time zone not null,
    committed_at timestamp(9) with time zone,
    pack_source varchar2(32 char),
    last_modified number(19,0),
    object_count number(19,0),
    delta_count number(19,0),
    index_version number(10,0),
    min_update_index number(19,0),
    max_update_index number(19,0),
    constraint pk_git_packs primary key (id),
    constraint uk_pack_repo_name_ext unique (repository_name, pack_name, pack_extension),
    constraint fk_pack_repository_lifecycle foreign key (repository_name)
        references git_repository_lifecycle (repository_name) on delete cascade
);

create index idx_pack_repo_committed on git_packs (repository_name, committed);
create index idx_pack_repo_lease
    on git_packs (repository_name, committed, write_lease_until);

create table git_pack_chunks (
    id number(19,0) generated by default as identity not null,
    pack_id number(19,0) not null,
    chunk_index number(10,0) not null,
    chunk_data blob not null,
    chunk_size number(10,0) not null,
    constraint pk_git_pack_chunks primary key (id),
    constraint uk_pack_chunk_index unique (pack_id, chunk_index),
    constraint fk_pack_chunk_pack foreign key (pack_id)
        references git_packs (id) on delete cascade
);

create table git_reflog (
    id number(19,0) generated by default as identity not null,
    version number(19,0),
    repository_name nvarchar2(255) not null,
    delivery_id nvarchar2(128),
    ref_name nvarchar2(1024) not null,
    ref_name_key nvarchar2(128) not null,
    old_id varchar2(40 char),
    new_id varchar2(40 char),
    who_name nvarchar2(255),
    who_email nvarchar2(255),
    who_when timestamp(9) with time zone not null,
    message nvarchar2(2000),
    constraint pk_git_reflog primary key (id)
);

create index idx_reflog_repo_ref_key_id
    on git_reflog (repository_name, ref_name_key, id desc);
create index idx_reflog_repo_delivery
    on git_reflog (repository_name, delivery_id);
