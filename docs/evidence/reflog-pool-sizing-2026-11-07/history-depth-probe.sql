-- Run with psql against a disposable PostgreSQL 17.10 database.
-- The temporary relation and all changes are removed by ROLLBACK.
BEGIN;
CREATE TEMP TABLE git_reflog (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT,
  repository_name VARCHAR(255) NOT NULL, delivery_id VARCHAR(128),
  ref_name VARCHAR(1024) NOT NULL, ref_name_key VARCHAR(128) NOT NULL,
  old_id VARCHAR(40), new_id VARCHAR(40), who_name VARCHAR(255), who_email VARCHAR(255),
  who_when TIMESTAMPTZ, message VARCHAR(2000)
);
CREATE INDEX idx_reflog_repo_ref_key_id ON git_reflog(repository_name, ref_name_key, id);
CREATE INDEX idx_reflog_repo_delivery ON git_reflog(repository_name, delivery_id);

-- Generate and execute the same query shape at three seeded history depths.
WITH setup AS (
  SELECT count, format($sql$
    TRUNCATE git_reflog RESTART IDENTITY;
    INSERT INTO git_reflog(repository_name, delivery_id, ref_name, ref_name_key, new_id)
    SELECT 'sizing-shared', 'sizing-'||i, 'refs/heads/producer-'||(i%%16),
           'refs/heads/producer-'||(i%%16), lpad(to_hex(i),40,'0')
    FROM generate_series(1,%s) i;
    $sql$, count) AS sql
  FROM (VALUES (128), (1024), (2048)) AS sizes(count)
), filter AS (
  SELECT string_agg(quote_literal('refs/heads/producer-'||i), ',') AS refs
  FROM generate_series(0,15) i
), query AS (
  SELECT format($sql$
    EXPLAIN (ANALYZE, BUFFERS, SETTINGS)
    SELECT r.ref_name, r.new_id FROM git_reflog r
    WHERE r.repository_name = 'sizing-shared'
      AND r.ref_name_key IN (%1$s) AND r.ref_name IN (%1$s)
      AND r.id = (
        SELECT MAX(candidate.id) FROM git_reflog candidate
        WHERE candidate.repository_name = r.repository_name
          AND candidate.ref_name_key = r.ref_name_key
          AND candidate.ref_name = r.ref_name
      );
    $sql$, refs) AS sql
  FROM filter
)
SELECT setup.sql || query.sql || 'ANALYZE git_reflog;' || query.sql
FROM setup CROSS JOIN query ORDER BY count
\gexec
ROLLBACK;
